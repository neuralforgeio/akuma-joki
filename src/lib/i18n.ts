const DICTS: Record<Lang, Dict> = { id: ID, en: EN };

type I18nState = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  _hasHydrated: boolean;
  setHasHydrated: (v: boolean) => void;
};

export const useI18n = create<I18nState>()(
  persist(
    (set, get) => ({
      lang: "id",
      _hasHydrated: false,
      setHasHydrated: (v) => set({ _hasHydrated: v }),
      setLang: (l) => set({ lang: l }),
      t: (key) => {
        const { lang } = get();
        return DICTS[lang][key] ?? DICTS.id[key] ?? key;
      },
    }),
    {
      name: "akuma-lang",
      // Skip automatic hydration so the first client render matches SSR (lang="id").
      // Hydration is triggered manually in <LanguageHydrationGate /> after mount.
      skipHydration: true,
      onRehydrateStorage: () => (state) => {
        state?.setHasHydrated(true);
      },
    }
  )
);
